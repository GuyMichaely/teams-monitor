import './smoke-env.mjs';
import assert from 'node:assert/strict';
import { copyFileSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { prepareAgenticHome } from './agentic-home.mjs';
import { ROOT, LOCAL_HOME } from '../src/local-paths.mjs';

const fixture = name => {
  const root = join(LOCAL_HOME, name);
  mkdirSync(join(root, 'config'), { recursive: true });
  copyFileSync(join(ROOT, 'config', 'config.example.yaml'), join(root, 'config', 'config.example.yaml'));
  writeFileSync(join(root, 'config', 'config.yaml'), 'live-config-sentinel');
  return root;
};
const root = fixture('private-checkout');
const home = prepareAgenticHome(root);
assert.equal(home, join(root, '.agentic-dev'));
assert.equal(readFileSync(join(root, 'config', 'config.yaml'), 'utf8'), 'live-config-sentinel');
const configFile = join(home, 'config', 'config.yaml');
const config = Bun.YAML.parse(readFileSync(configFile, 'utf8'));
assert.equal(config.gui.port, 28090);
assert.equal(config.gui.authTokenEnv, 'AGENTIC_GUI_TOKEN');
assert.equal(config.controlWorker.enabled, false);
assert.equal(config.controlWorker.publicHealthUrl, '');
assert.equal(config.desktop.keepAwake, false);
assert.deepEqual(config.alerts.fcm, {});
assert.deepEqual(config.replyPolicy.entries, []);
assert(!readFileSync(join(home, 'context', 'user-profile.md'), 'utf8').includes('=== USER PROFILE ==='));
config.brain.model = 'development-model';
writeFileSync(configFile, Bun.YAML.stringify(config));
prepareAgenticHome(root);
assert.equal(Bun.YAML.parse(readFileSync(configFile, 'utf8')).brain.model, 'development-model', 'Initialization must preserve existing development config');
config.gui.port = 8090;
writeFileSync(configFile, Bun.YAML.stringify(config));
assert.throws(() => prepareAgenticHome(root), /separate loopback/);

const redirected = fixture('redirected-checkout');
const target = join(LOCAL_HOME, 'directory-link-target');
mkdirSync(target);
symlinkSync(target, join(redirected, '.agentic-dev'), process.platform === 'win32' ? 'junction' : 'dir');
assert.throws(() => prepareAgenticHome(redirected), /directory links/);
assert.equal(readFileSync(join(redirected, 'config', 'config.yaml'), 'utf8'), 'live-config-sentinel');
console.log('Agentic development home smoke passed: separate state, ports/auth, preserved configuration and link refusal.');
